#!/usr/bin/env python3
"""Rasterize the dashboard's TTFs into 1-bit Adafruit GFX fonts for the firmware.

  python3 dashboard/gen_fonts.py   # writes firmware/src/dash_fonts.h

Glyphs are rendered with PIL (antialiased, then thresholded like the rest of the screen), so the
device draws the same shapes a PIL preview would. Each font also gets its ascent/descent so the
firmware can anchor text the way PIL's "la"/"lm"/"ra"... anchors do.
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "src", "dash_fonts.h")
THRESHOLD = 140
FIRST, LAST = 0x20, 0x7E

# name: (file, px size, variation)
FONTS = {
    "BIG18": ("ArchivoBlack-Regular.ttf", 18, None),
    "BIG22": ("ArchivoBlack-Regular.ttf", 22, None),
    "BIG40": ("ArchivoBlack-Regular.ttf", 40, None),
    "PIX8": ("Silkscreen-Regular.ttf", 8, None),
    "PIXB8": ("Silkscreen-Bold.ttf", 8, None),
    "MONO18B": ("JetBrainsMono.ttf", 18, "Bold"),
    "MONO13B": ("JetBrainsMono.ttf", 13, "Bold"),
    "MONO12B": ("JetBrainsMono.ttf", 12, "Bold"),
    "MONO12M": ("JetBrainsMono.ttf", 12, "Medium"),
    "MONO11R": ("JetBrainsMono.ttf", 11, "Regular"),
    "MONO12R": ("JetBrainsMono.ttf", 12, "Regular"),
    "SANS12M": ("SpaceGrotesk.ttf", 12, "Medium"),
    "SANS13M": ("SpaceGrotesk.ttf", 13, "Medium"),
}


def glyph(f, ch):
    pad = f.size * 2
    img = Image.new("L", (pad * 3, pad * 3), 255)
    ImageDraw.Draw(img).text((pad, pad * 2), ch, font=f, fill=0, anchor="ls")
    bw = img.point(lambda v: 0 if v < THRESHOLD else 255, mode="1")
    adv = round(f.getlength(ch))
    box = Image.eval(bw.convert("L"), lambda v: 255 - v).getbbox()
    if not box:
        return [], 0, 0, adv, 0, 0
    x0, y0, x1, y1 = box
    bits = []
    px = bw.load()
    for y in range(y0, y1):
        for x in range(x0, x1):
            bits.append(1 if px[x, y] == 0 else 0)
    return bits, x1 - x0, y1 - y0, adv, x0 - pad, y0 - pad * 2


def main():
    out = ["// generated by dashboard/gen_fonts.py - do not edit", "#pragma once",
           "#include <Adafruit_GFX.h>", "",
           "struct DashFont { const GFXfont* gfx; int8_t ascent, descent; };", ""]
    for name, (file, size, var) in FONTS.items():
        f = ImageFont.truetype(os.path.join(HERE, "fonts", file), size)
        if var:
            f.set_variation_by_name(var)
        asc, desc = f.getmetrics()
        bitmap, glyphs = [], []
        for c in range(FIRST, LAST + 1):
            bits, w, h, adv, xo, yo = glyph(f, chr(c))
            glyphs.append((len(bitmap) // 8, w, h, adv, xo, yo))
            bits += [0] * (-len(bits) % 8)  # each glyph starts on a byte boundary
            bitmap += bits
        data = [sum(b << (7 - i) for i, b in enumerate(bitmap[j:j + 8])) for j in range(0, len(bitmap), 8)]
        out.append(f"const uint8_t {name}_bm[] PROGMEM = {{")
        for j in range(0, len(data), 24):
            out.append("  " + ",".join(f"0x{v:02x}" for v in data[j:j + 24]) + ",")
        out.append("};")
        out.append(f"const GFXglyph {name}_gl[] PROGMEM = {{")
        for g in glyphs:
            out.append("  {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(f"const GFXfont {name}_gfx PROGMEM = {{(uint8_t*){name}_bm, (GFXglyph*){name}_gl, "
                   f"0x{FIRST:02x}, 0x{LAST:02x}, {asc + desc}}};")
        out.append(f"const DashFont {name} = {{&{name}_gfx, {asc}, {desc}}};")
        out.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(out))
    print("wrote", os.path.relpath(OUT), f"({os.path.getsize(OUT) // 1024} KB source)")


if __name__ == "__main__":
    main()
